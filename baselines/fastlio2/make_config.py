#!/usr/bin/env python3
"""FAST-LIO2 configuration for one dataset = the upstream defaults for its point-cloud input type 4
(marsim_upstream_7cc4175.yaml: config/marsim.yaml and the parameters of launch/mapping_marsim.launch at 7cc4175) with
the sensor description taken from our dataset config (topics, depth -> IMU extrinsic, time offset, and the depth image's
scale and valid range: the bridge's range filter; blind = minimum range) and the scan filter, IMU noise, and iteration
count of the upstream FAST-LIVO2 depth baseline of the paper (the probe chose these over the FAST-LIO2 defaults,
7 vs 4 of 16 sequences tracked below 1 m).  Output-only switches (scan and path publishing, PCD saving) are off.
TAU, the trigger of the restriction module, is written when given (fixed per dataset from the logging pass of the
unrestricted filter); the variant files (e14_*.yaml) set the module's mode.

Usage: make_config.py OUR_BASE_CFG OUT_CFG [TAU]"""
import sys
from pathlib import Path

import yaml

ours, out = yaml.safe_load(open(sys.argv[1])), sys.argv[2]
cfg = yaml.safe_load(open(Path(__file__).resolve().parent / 'marsim_upstream_7cc4175.yaml'))
c, d, t = ours['common'], ours['depth'], ours.get('time_offset', {})
cfg['common'].update(lid_topic='/depth_cloud', imu_topic=c['imu_topic'],
                     time_offset_lidar_to_imu=float(t.get('depth_time_offset', 0.0)))
cfg['preprocess']['blind'] = float(d['min_depth'])
cfg['mapping'].update(extrinsic_T=ours['extrin_calib']['extrinsic_T'], extrinsic_R=ours['extrin_calib']['extrinsic_R'],
                      acc_cov=0.5, gyr_cov=0.3, b_acc_cov=0.0001, b_gyr_cov=0.0001)   # upstream FAST-LIVO2 depth baseline
cfg.update(filter_size_surf=0.1, max_iteration=5)                                     # upstream FAST-LIVO2 depth baseline
cfg['publish'].update(path_en=False, scan_publish_en=False, dense_publish_en=False, scan_bodyframe_pub_en=False)
cfg['pcd_save']['pcd_save_en'] = False
cfg['depth_bridge'] = dict(depth_topic=c['depth_topic'], info_topic=c['depth_info_topic'], cloud_topic='/depth_cloud',
                           depth_scale=float(d['depth_scale']), min_depth=float(d['min_depth']),
                           max_depth=float(d['max_depth']), fourth_field='intensity')
if len(sys.argv) > 3:
    cfg['e14'] = dict(tau=float(sys.argv[3]))
with open(out, 'w') as f:
    f.write(f'# Generated by baselines/fastlio2/make_config.py from {Path(sys.argv[1]).name}:\n'
            '# upstream FAST-LIO2 defaults (input type 4, config/marsim.yaml at 7cc4175) + this dataset\'s sensor description\n'
            '# + scan filter, IMU noise, and iterations of the upstream FAST-LIVO2 depth baseline of the paper.\n')
    yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=None)
print('wrote', out)
